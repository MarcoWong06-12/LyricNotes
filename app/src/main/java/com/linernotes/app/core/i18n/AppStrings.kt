/**
 * 支持的应用界面语言
 */
enum class AppLanguage(val code: String, val displayName: String) {
    SYSTEM("system", "跟随系统"),
    ZH_CN("zh-CN", "简体中文"),
    ZH_TW("zh-TW", "繁體中文"),
    EN("en", "English"),
    JA("ja", "日本語");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) } ?: SYSTEM
    }
}

/**
 * 歌词翻译目标语言
 */
