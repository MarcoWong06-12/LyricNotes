    ZH_TW("zh-TW", "繁體中文", "中文（繁體）", "zh-TW"),
    EN("en", "English", "English", "en"),
    JA("ja", "日本語", "日本語", "ja"),
    KO("ko", "한국어", "한국어", "ko"),
    FR("fr", "Français", "Français", "fr"),
    ES("es", "Español", "Español", "es"),
